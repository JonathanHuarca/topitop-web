import {
  Look,
  MaterialComponent,
  Product,
  QualitySheet,
  TraceabilityStep,
} from '../types';

function makeQualitySheet(params: {
  plant: 'Lima' | 'Chincha';
  materials: MaterialComponent[];
  rawMaterialsOrigin: string;
  manufacturingProcess: string;
  care: string;
  hasOekoTex: boolean;
  supplierInfo?: string;
  productionConditions?: string;
  exportNote?: string;
}): QualitySheet {
  const composition = params.materials
    .map((m) => `${m.percentage}% ${m.name}`)
    .join(', ');

  const plantDetail =
    params.plant === 'Lima'
      ? 'Planta industrial Topitop — San Juan de Lurigancho, Lima, Perú'
      : 'Planta industrial Topitop — Chincha, Ica, Perú';

  const supplierInfo =
    params.supplierInfo ??
    'Confección en planta propia Topitop (Perú). Identidad de proveedores externos de hilado/avíos: No disponible públicamente.';

  const productionConditions =
    params.productionConditions ??
    (params.hasOekoTex
      ? 'Producción en planta textil propia en el Perú bajo estándares de exportación y verificación OEKO-TEX® Standard 100. Auditorías externas por lote: No disponibles en esta ficha.'
      : 'Producción en planta textil propia en el Perú bajo control interno de calidad. Certificaciones externas específicas de esta referencia: No disponibles.');

  const traceability: TraceabilityStep[] = [
    {
      stage: '1. Origen de materias primas',
      location: params.rawMaterialsOrigin,
      detail: params.materials
        .map((m) => `${m.percentage}% ${m.name} (${m.origin})`)
        .join(' · '),
      verified: !params.rawMaterialsOrigin.toLowerCase().includes('no disponible'),
    },
    {
      stage: '2. Transformación textil',
      location: `${params.plant}, Perú`,
      detail: params.manufacturingProcess,
      verified: true,
    },
    {
      stage: '3. Confección y control de calidad',
      location: plantDetail,
      detail:
        params.exportNote ??
        'Corte, costura, planchado y control pieza por pieza en planta Topitop.',
      verified: true,
    },
    {
      stage: '4. Distribución y punto de venta',
      location: 'Centro de distribución Lima → Tiendas Topitop y Web',
      detail:
        'Etiquetado con referencia SKU y código QR vinculado a esta ficha digital.',
      verified: true,
    },
  ];

  return {
    origin: 'Hecho en el Perú',
    originCountry: 'Perú',
    plant: params.plant,
    plantDetail,
    composition,
    materials: params.materials,
    rawMaterialsOrigin: params.rawMaterialsOrigin,
    manufacturingProcess: params.manufacturingProcess,
    supplierInfo,
    productionConditions,
    care: params.care,
    hasOekoTex: params.hasOekoTex,
    oekoTexStatus: params.hasOekoTex
      ? 'Certificación OEKO-TEX® Standard 100 declarada por marca (N.° de lote verificable en etiqueta física; registro público por lote: No disponible).'
      : 'No aplica / Certificación Oeko-Tex no registrada para esta referencia.',
    oekoTexSummary: params.hasOekoTex
      ? 'Garantiza textiles libres de sustancias nocivas en concentraciones perjudiciales para la piel.'
      : 'Esta prenda no cuenta con sello Oeko-Tex declarado en ficha; información pendiente de actualización.',
    exportNote:
      params.exportNote ??
      'Confeccionada en plantas peruanas con estándares de calidad de exportación.',
    traceability,
  };
}

