export function formatPen(amount: number): string {
  return `S/ ${amount.toFixed(2)}`;
}

export function computeLookPrice(
  prices: number[],
  discountPercent = 10
): { original: number; discounted: number; savings: number } {
  const original = Number(prices.reduce((a, b) => a + b, 0).toFixed(2));
  const rawDiscounted = original * (1 - discountPercent / 100);
  const discounted = Number((Math.ceil(rawDiscounted * 10) / 10).toFixed(2));
  const savings = Number((original - discounted).toFixed(2));
  return { original, discounted, savings };
}
